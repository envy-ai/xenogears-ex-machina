import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';

interface TraceEntry { request: unknown; response: unknown }
interface DraftParityFixture { synthetic_only: true; trace: TraceEntry[] }

async function send(page: import('@playwright/test').Page, command: unknown): Promise<unknown> {
  await expect.poll(() => page.evaluate(() =>
    typeof (window as unknown as { __xemStudioTest?: { command?: unknown } }).__xemStudioTest?.command === 'function'))
    .toBe(true);
  return page.evaluate((request) => {
    const driver = (window as unknown as { __xemStudioTest: { command(json: string): string } }).__xemStudioTest;
    return JSON.parse(driver.command(JSON.stringify(request))) as unknown;
  }, command);
}

test('matches native draft protocol replies through wasm for the same synthetic edit trace', async ({ page }) => {
  const fixturePath = process.env.XEM_STUDIO_WASM_DRAFT_PARITY_FIXTURE;
  test.skip(!fixturePath, 'native draft protocol fixture is generated by the focused Rust test');
  const fixture = JSON.parse(readFileSync(fixturePath!, 'utf8')) as DraftParityFixture;
  expect(fixture.synthetic_only).toBe(true);
  expect(fixture.trace.length).toBeGreaterThan(8);

  await page.goto('/');
  await expect(page.locator('[data-panel-id="backend"]')).toContainText('xem-studio 0.5.0');
  for (const [index, step] of fixture.trace.entries()) {
    expect(await send(page, step.request), `native/WASM response at trace step ${index}`).toEqual(step.response);
  }
});
