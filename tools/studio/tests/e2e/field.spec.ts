import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';

async function send(page: import('@playwright/test').Page, command: unknown) {
  const response = page.getByLabel('Backend response');
  const before = await response.textContent();
  await page.getByLabel('Command (JSON)').fill(JSON.stringify(command));
  await page.getByRole('button', { name: 'Send command' }).click();
  await expect.poll(async () => {
    const text = await response.textContent();
    if (!text || text === before || text === 'Send a command to see its reply.') return undefined;
    try { return JSON.parse(text); } catch { return undefined; }
  }).not.toBeUndefined();
  const text = await response.textContent();
  return JSON.parse(text ?? 'null') as unknown;
}

test('runs field decode and exact encode round trip through the loaded wasm service', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('[data-panel-id="backend"]')).toContainText('xem-studio 0.5.0');

  const bytes = Array(197).fill(0) as number[];
  bytes[128] = 1; // one actor; its 32 zero event entries point at bytecode PC 0
  const graph = await send(page, {
    op: 'field.decode',
    args: { bytes, declared_size: bytes.length },
  }) as { schema_version: number; instructions: Array<{ pc: number; spec: { mnemonic: string } }> };
  expect(graph.schema_version).toBe(1);
  expect(graph.instructions).toEqual([{ ...graph.instructions[0], pc: 0 }]);
  expect(graph.instructions[0]?.spec.mnemonic).toBe('end_slot');

  const encoded = await send(page, { op: 'field.encode', args: { graph } });
  expect(encoded).toEqual(bytes);
});

test('matches the native graph field-for-field through the loaded wasm service', async ({ page }) => {
  const fixturePath = process.env.XEM_STUDIO_WASM_PARITY_FIXTURE;
  test.skip(!fixturePath, 'native parity fixture is generated by the focused Rust test');
  const fixture = JSON.parse(readFileSync(fixturePath!, 'utf8')) as {
    bytes: number[];
    declared_size: number;
    graph: unknown;
  };

  await page.goto('/');
  await expect(page.locator('[data-panel-id="backend"]')).toContainText('xem-studio 0.5.0');
  const graph = await send(page, {
    op: 'field.decode',
    args: { bytes: fixture.bytes, declared_size: fixture.declared_size },
  });
  expect(graph).toEqual(fixture.graph);
  const encoded = await send(page, { op: 'field.encode', args: { graph: fixture.graph } });
  expect(encoded).toEqual(fixture.bytes);
});

test('keeps field errors distinct from successful error-shaped echo data', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('[data-panel-id="backend"]')).toContainText('xem-studio 0.5.0');

  const bytes = Array(198).fill(0) as number[];
  bytes[128] = 1;
  bytes[196] = 0xfe;
  bytes[197] = 0xff;
  await send(page, { op: 'field.decode', args: { bytes, declared_size: bytes.length } });
  const errors = page.getByRole('alert', { name: 'Studio errors' });
  await expect(errors).toContainText('unsupported_instruction');

  const value = { error: { kind: 'user-data', message: 'ordinary successful JSON' }, ok: null };
  expect(await send(page, { op: 'echo', args: value })).toEqual(value);
  await expect(errors).toContainText('unsupported_instruction');
});
